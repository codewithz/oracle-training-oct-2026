SET DEFINE OFF
SET FEEDBACK OFF

BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('MEASUREMENTS','WAFERS','LOTS','TOOLS','PRODUCTS')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

CREATE TABLE products (
  product_id     NUMBER(4)     CONSTRAINT products_pk PRIMARY KEY,
  product_code   VARCHAR2(12)  NOT NULL CONSTRAINT products_code_uk UNIQUE,
  family         VARCHAR2(20)  NOT NULL,
  diameter_mm    NUMBER(3)     NOT NULL,
  target_thk_nm  NUMBER(8,2)   NOT NULL
);

CREATE TABLE tools (
  tool_id    VARCHAR2(6)   CONSTRAINT tools_pk PRIMARY KEY,
  tool_type  VARCHAR2(12)  NOT NULL,
  bay        VARCHAR2(4)   NOT NULL
);

CREATE TABLE lots (
  lot_id         VARCHAR2(12)  CONSTRAINT lots_pk PRIMARY KEY,
  product_id     NUMBER(4)     NOT NULL CONSTRAINT lots_product_fk REFERENCES products,
  lot_type       VARCHAR2(8)   NOT NULL CONSTRAINT lots_type_ck CHECK (lot_type IN ('PROD','SPLIT','REWORK')),
  parent_lot_id  VARCHAR2(12)  CONSTRAINT lots_parent_fk REFERENCES lots,
  start_date     DATE          NOT NULL,
  status         VARCHAR2(8)   NOT NULL CONSTRAINT lots_status_ck CHECK (status IN ('ACTIVE','HOLD','SHIPPED','SCRAPPED')),
  priority       NUMBER(1)     NOT NULL,
  hold_reason    VARCHAR2(60)
);

CREATE TABLE wafers (
  wafer_id  VARCHAR2(16)  CONSTRAINT wafers_pk PRIMARY KEY,
  lot_id    VARCHAR2(12)  NOT NULL CONSTRAINT wafers_lot_fk REFERENCES lots,
  slot_no   NUMBER(2)     NOT NULL,
  grade     VARCHAR2(6)   CONSTRAINT wafers_grade_ck CHECK (grade IN ('PRIME','TEST','SCRAP'))
);

CREATE TABLE measurements (
  meas_id       NUMBER(6)     CONSTRAINT measurements_pk PRIMARY KEY,
  wafer_id      VARCHAR2(16)  NOT NULL CONSTRAINT meas_wafer_fk REFERENCES wafers,
  step          VARCHAR2(8)   NOT NULL CONSTRAINT meas_step_ck CHECK (step IN ('SPLIT','ANNEAL','FINAL')),
  tool_id       VARCHAR2(6)   NOT NULL CONSTRAINT meas_tool_fk REFERENCES tools,
  meas_time     DATE          NOT NULL,
  thickness_nm  NUMBER(8,2)   NOT NULL,
  defect_count  NUMBER(5)     NOT NULL
);

CREATE INDEX lots_product_ix   ON lots (product_id);
CREATE INDEX lots_parent_ix    ON lots (parent_lot_id);
CREATE INDEX wafers_lot_ix     ON wafers (lot_id);
CREATE INDEX meas_wafer_ix     ON measurements (wafer_id);
CREATE INDEX meas_tool_time_ix ON measurements (tool_id, meas_time);


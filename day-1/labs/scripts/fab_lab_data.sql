-- A small, invented wafer-fab data set used for every Day 1 SQL exercise:
--   PRODUCTS      5 substrate products (one has no lots yet)
--   TOOLS         9 process and metrology tools (two never used)
--   LOTS          lots with split and rework genealogy (PARENT_LOT_ID)
--   WAFERS        wafers per lot
--   MEASUREMENTS  thickness and defect readings per wafer and step
-- Product names and numbers are illustrative, not real data from any company.
